"""
Andhra Pradesh Legislature — Bills scraper.
Source: https://aplegislature.org/web/aplegislature/bills

WHY THIS SOURCE
Bills are the primary record of what the Assembly actually legislated, as
opposed to what was announced. Until now the platform had the Assembly's
notice board (NeVA) but not the Bills register, which meant a claim like
"the government passed a law on X" had no document behind it.

WHAT THE PAGE IS
A Liferay DXP portal. The bills table is rendered by a portlet whose instance
id appears in every one of its control names:

    _BillReport_APPortlet_INSTANCE_xb6VplcPP2zK_term_id

That instance id is generated by Liferay and is stable only as long as the
page layout is not rebuilt. So it is NOT hardcoded as a constant: the scraper
reads whatever `*_term_id` select the page actually contains and uses that
name. If the portlet is re-instanced, this keeps working; if the control
disappears entirely, the scraper falls back to the default term the page
serves and says so in the log, rather than silently scraping nothing.

Columns, as served (verified from the live page, XVI Assembly, 89 rows):
    Sl No. | Title of the Bill | Legislative Assembly |
    Passed in Legislative Council | Date of Publication in Official Gazette |
    Introduced On | Passed On

Bill PDFs live on a different host:
    https://legislation.aplegislature.org/PreviewPage.do?filePath=basePath&fileName=Bills/...

TERMS
Three are offered at the time of writing: XVI (2024-2029), XV (2019-2024),
XIV (2014-2019). All are scraped — a transparency platform holding only the
current government's bills is not much of a transparency platform.

Switching term is a POST, not a query parameter. That distinction cost a run:
sent as GET, the portal ignored it and served the current term three times,
and the scraper logged "86 rows" for each Assembly while having collected one.
So the scraper now compares each term's row set against the ones before it and
refuses to file a repeat as another Assembly's record.

A row without a usable PDF link is still saved: for a bill, the title, the
dates and the Assembly term are themselves the record, and the gazette
citation is what a reader needs. Such rows carry source_url = None and
source_page_url = the bills page, so the UI can still say where it came from.
"""

import asyncio
from datetime import datetime, timezone
from typing import Optional
from urllib.parse import urljoin
import re

from bs4 import BeautifulSoup
from sqlalchemy import select

from app.config import settings
from app.scrapers.base import BaseScraper
from app.scrapers.sanity import FieldRule, SanityAbort, SanitySpec
from app.database import get_db_context
from app.models.document import Document, DocumentType
from app.utils.logger import logger

BASE = "https://aplegislature.org"
# Verified against the live site. An earlier version used /web/guest/bills,
# which 404s — Liferay serves this portal under the "aplegislature" site
# scope, not the default guest scope, and every bill was silently missed.
BILLS_URL = f"{BASE}/web/aplegislature/bills"
PORTAL_NAME = "AP Legislature — Bills"

# Terms are NOT hardcoded: the list, the posted values and the year ranges are
# all read off the live selector (see _discover_terms). A hardcoded list would
# go stale the day the XVII Assembly is seated, and silently keep scraping only
# the terms this file happened to know about.

# Header text -> the field we want. Matched loosely (lowercased, squashed),
# because government tables rename columns more often than they restructure.
COLUMN_HINTS = {
    "title": ("title of the bill", "title", "bill name"),
    "assembly": ("legislative assembly",),
    "council": ("legislative council", "passed in legislative council"),
    "gazette": ("gazette", "date of publication"),
    "introduced": ("introduced",),
    "passed": ("passed on",),
}


def squash(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


class APLegislatureBillsScraper(BaseScraper):
    PORTAL_NAME = "AP_Legislature_Bills"
    BASE_URL = BASE
    # No key_field on purpose. A bill title repeats legitimately across
    # assemblies ("The Andhra Pradesh Appropriation Bill"), so a uniqueness
    # check on it would abort a correct run. Repetition within one term is
    # already caught by the duplicate-term guard in _discover_terms.
    SANITY = SanitySpec(
        min_rows=1,
        fields={
            "title": FieldRule(required=True, min_len=8, max_len=500),
            "gazette_date": FieldRule(min_year=1950, max_year_ahead=1),
            "introduced_on": FieldRule(min_year=1950, max_year_ahead=1),
            "passed_on": FieldRule(min_year=1950, max_year_ahead=1),
        },
    )

    async def scrape(self) -> int:
        self.log_start()
        total = 0
        failure: BaseException | None = None
        try:
            term_param, options = await self._discover_terms()
            if not options:
                options = [(None, "current")]

            seen_signatures: set[tuple] = set()
            for value, label in options:
                rows = await self._fetch_term(term_param, value)
                if not rows:
                    logger.warning(f"[{self.PORTAL_NAME}] Term {label}: no rows")
                    continue

                # If the portal ignores the term we posted it silently serves
                # the default term again. Identical row sets across two terms
                # means the switch did not take, and quietly saving them as a
                # second Assembly's bills would be a false record — so say so.
                signature = tuple(sorted(r["title"] for r in rows))
                if signature in seen_signatures:
                    logger.warning(
                        f"[{self.PORTAL_NAME}] Term {label} returned exactly the rows of an "
                        f"earlier term — the term switch is not taking effect. Skipping; "
                        f"this Assembly's bills are NOT collected."
                    )
                    continue
                seen_signatures.add(signature)

                start_year, end_year = self._term_years(label)
                saved = await self._save(rows, label, start_year, end_year)
                total += saved
                logger.info(f"[{self.PORTAL_NAME}] Term {label}: {len(rows)} rows, {saved} new")
        except SanityAbort:
            raise
        except Exception as e:
            self.log_error("Scrape failed", e)
            failure = e
        finally:
            await self.close()
        return self.finish(total, failure)

    def _term_years(self, label: str) -> tuple[Optional[int], Optional[int]]:
        """Pull "(2024 - 2029)" out of the option label the portal supplied."""
        found = [int(m) for m in re.findall(r"((?:19|20)\d{2})", label)]
        if len(found) >= 2:
            return found[0], found[1]
        if len(found) == 1:
            return found[0], None
        return None, None

    async def _discover_terms(self) -> tuple[Optional[str], list[tuple[str, str]]]:
        """
        Read the term selector's name AND its real option values off the page.

        Two things here were guessed once and both were wrong, so both are now
        read from the live HTML:

        1. The control name. Liferay namespaces it with the portlet instance id
           (_BillReport_APPortlet_INSTANCE_xb6VplcPP2zK_term_id), which changes
           if the page is rebuilt.
        2. The option VALUES. The labels read "XVI (2024 - 2029)", but the value
           the form actually posts is the portal's own term id — typically a
           number. Posting the roman numeral silently returned the default term
           three times, so the scraper reported 86 rows for all three terms and
           collected only the current Assembly.

        Returns (control name, [(value, label), ...]).
        """
        try:
            r = await self.fetch(BILLS_URL)
            soup = BeautifulSoup(r.text, "lxml")
            for sel in soup.find_all("select"):
                name = sel.get("name") or sel.get("id") or ""
                if not (name.endswith("_term_id") or "term" in name.lower()):
                    continue
                options = []
                for o in sel.find_all("option"):
                    value = (o.get("value") or "").strip()
                    label = squash(o.get_text())
                    # "--Select Term--" is a prompt, not a term.
                    if not value or "select" in label.lower():
                        continue
                    options.append((value, label))
                logger.info(
                    f"[{self.PORTAL_NAME}] Term selector {name} -> "
                    + ", ".join(f"{v}={l}" for v, l in options)
                )
                return name, options
        except Exception as e:
            logger.warning(f"[{self.PORTAL_NAME}] Could not read term selector: {e}")
        logger.warning(f"[{self.PORTAL_NAME}] No term selector found — scraping the default term only")
        return None, []

    def _action_url(self, term_param: str) -> str:
        """
        Rebuild the Liferay render URL the page's own JavaScript submits to.

        This is the crux of the whole scraper. The form has no action attribute;
        its handler calls submitForm(form, <url>) with a URL carrying Liferay's
        portlet routing parameters:

            .../bills?p_p_id=<portlet>&p_p_lifecycle=0&p_p_state=normal&p_p_mode=view

        Posting the term to the bare page URL — which two earlier versions did —
        is not an error Liferay reports. It cannot tell which portlet the
        parameter belongs to, so it drops it and renders the default term. The
        scrape then "succeeds" with the current Assembly's bills labelled as
        three different Assemblies, which is worse than failing.

        The portlet id is the control name without its leading underscore and
        trailing "_term_id", so it is derived from what the page gave us rather
        than hardcoded — the instance id changes if the page is rebuilt.
        """
        portlet = term_param.lstrip("_")
        if portlet.endswith("_term_id"):
            portlet = portlet[: -len("_term_id")]
        return (
            f"{BILLS_URL}?p_p_id={portlet}&p_p_lifecycle=0"
            f"&p_p_state=normal&p_p_mode=view"
        )

    async def _fetch_term(self, term_param: Optional[str], value: Optional[str]) -> list[dict]:
        """
        Fetch one Assembly term by posting the term id to the portlet's own
        render URL (see _action_url). With no selector on the page, only the
        default term is fetched, once.
        """
        try:
            if term_param and value:
                await asyncio.sleep(settings.scraper_request_delay)
                r = await self.client.post(
                    self._action_url(term_param),
                    data={term_param: value},
                    headers={"Referer": BILLS_URL},
                )
                r.raise_for_status()
            else:
                r = await self.fetch(BILLS_URL)
        except Exception as e:
            logger.warning(f"[{self.PORTAL_NAME}] Term {value or 'default'} fetch failed: {e}")
            return []

        soup = BeautifulSoup(r.text, "lxml")
        table = self._pick_table(soup)
        if table is None:
            return []
        return self._parse_table(table)

    def _pick_table(self, soup) -> Optional[object]:
        """
        The page carries layout tables as well as the bills table. Choose the
        one whose header actually mentions a bill — matching on structure, not
        on position, so a new banner table above it does not break the scrape.
        """
        best = None
        best_rows = 0
        for t in soup.find_all("table"):
            head = " ".join(squash(c.get_text()).lower() for c in t.find_all("th")[:10])
            if "bill" not in head:
                continue
            rows = len(t.find_all("tr"))
            if rows > best_rows:
                best, best_rows = t, rows
        return best

    def _parse_table(self, table) -> list[dict]:
        headers = [squash(th.get_text()).lower() for th in table.find_all("th")]
        index: dict[str, int] = {}
        for field, hints in COLUMN_HINTS.items():
            for i, h in enumerate(headers):
                if any(hint in h for hint in hints):
                    index[field] = i
                    break

        if "title" not in index:
            logger.warning(f"[{self.PORTAL_NAME}] No title column in headers: {headers}")
            return []

        out: list[dict] = []
        for tr in table.find_all("tr"):
            cells = tr.find_all("td")
            # The table interleaves session banners ("Session VII") among the
            # bill rows — a single wide cell, not a bill. Verified on the live
            # page: without this they would be saved as bills titled "Session
            # VII", which is exactly the sort of junk row that makes a
            # transparency archive untrustworthy.
            if len(cells) < len(headers) - 2:   # tolerate a missing trailing cell
                continue

            def cell(field: str) -> str:
                i = index.get(field)
                return squash(cells[i].get_text()) if i is not None and i < len(cells) else ""

            title = cell("title")
            if not title or len(title) < 5:
                continue
            # A real bill always says so. This also drops any stray banner row
            # that happened to carry enough cells to get this far.
            if "bill" not in title.lower():
                continue

            pdf = None
            ti = index["title"]
            if ti < len(cells):
                link = cells[ti].find("a", href=True)
                if link:
                    pdf = urljoin(BILLS_URL, link["href"])

            out.append({
                "title": title,
                "pdf_url": pdf,
                "assembly": cell("assembly"),
                "council": cell("council"),
                "gazette_date": self._date(cell("gazette")),
                "introduced_on": self._date(cell("introduced")),
                "passed_on": self._date(cell("passed")),
                "gazette_raw": cell("gazette"),
            })
        return out

    def _date(self, text: str) -> Optional[datetime]:
        text = squash(text)
        if not text or text.lower() in ("-", "na", "n/a", "nil"):
            return None
        for fmt in ("%d-%m-%Y", "%d/%m/%Y", "%d-%b-%Y", "%d %B %Y", "%Y-%m-%d", "%d.%m.%Y"):
            try:
                return datetime.strptime(text, fmt).replace(tzinfo=timezone.utc)
            except ValueError:
                continue
        return None

    def _reference(self, title: str) -> Optional[str]:
        # "The A.P. Xyz (Amendment) Bill, 2025 (L.A. Bill No. 12 of 2025)"
        m = re.search(r"(?:Bill\s*No\.?\s*|L\.?A\.?\s*Bill\s*No\.?\s*)(\d+)\s*of\s*(\d{4})", title, re.I)
        return f"Bill No. {m.group(1)} of {m.group(2)}" if m else None

    @staticmethod
    def _ordinal(label: str) -> str:
        """"XVI (2024 - 2029)" -> "XVI", for prose that already gives the years."""
        return re.split(r"[\s(]", squash(label), 1)[0] or squash(label)

    async def _save(self, rows: list[dict], term: str, start_year: int, end_year: int) -> int:
        rows = await self.gate(rows)
        saved = 0
        now = datetime.now(timezone.utc)
        async with get_db_context() as db:
            for r in rows:
                try:
                    # Dedupe on the PDF when there is one, otherwise on the exact
                    # title within the same term — a bill title is unique inside
                    # an Assembly term, and two terms can legitimately carry the
                    # same title for two different bills.
                    if r["pdf_url"]:
                        dupe = await db.execute(
                            select(Document).where(Document.source_url == r["pdf_url"])
                        )
                    else:
                        dupe = await db.execute(
                            select(Document).where(
                                Document.title == r["title"][:500],
                                Document.source_portal == PORTAL_NAME,
                                Document.department == f"{term} Assembly",
                            )
                        )
                    if dupe.scalar_one_or_none():
                        continue

                    year = None
                    for d in (r["passed_on"], r["introduced_on"], r["gazette_date"]):
                        if d:
                            year = d.year
                            break
                    if year is None:
                        m = re.search(r"\b(19|20)\d{2}\b", r["title"])
                        year = int(m.group(0)) if m else start_year

                    bits = []
                    if r["assembly"]:
                        bits.append(f"Legislative Assembly: {r['assembly']}")
                    if r["council"]:
                        bits.append(f"Legislative Council: {r['council']}")
                    if r["gazette_raw"]:
                        bits.append(f"Gazette publication: {r['gazette_raw']}")
                    # `term` is the page's own label and already carries the
                    # years ("XVI (2024 - 2029)"), so only the ordinal is used
                    # here — otherwise the line reads "... (2024 - 2029)
                    # Assembly (2024-2029)".
                    bits.append(f"{self._ordinal(term)} Assembly ({start_year}-{end_year})")

                    db.add(Document(
                        title=r["title"][:500],
                        document_type=DocumentType.ASSEMBLY_BILL,
                        year=year,
                        department=f"{term} Assembly",
                        reference_number=self._reference(r["title"]),
                        description=" · ".join(bits),
                        source_url=r["pdf_url"],
                        source_portal=PORTAL_NAME,
                        source_page_url=BILLS_URL,
                        source_page_title=f"AP Legislature — Bills ({term} Assembly)",
                        retrieved_at=now,
                        published_date=r["gazette_date"] or r["passed_on"] or r["introduced_on"],
                        last_scraped_at=now,
                    ))
                    saved += 1
                except Exception as ex:
                    logger.warning(f"[{PORTAL_NAME}] Save failed for '{r.get('title','')[:60]}': {ex}")
        return saved
